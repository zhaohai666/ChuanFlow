"""Incompressible Navier-Stokes family Python binding tests (CTest `python.ns`).

Covers two laminar drivers exposed by chflow_core:
  * `solve_piso_ns_case`: transient PISO on the start-up channel; the anchors
    mirror tests/check_piso.py: the analytic start-up series with the discrete
    half-cell wall offset, monotone start-up without overshoot, and a
    divergence-free corrected flux.
  * `solve_simple_ns_case`: steady SIMPLE on the Poiseuille channel; the
    anchors mirror tests/check_poiseuille.py: developed parabolic profile,
    vanishing transverse velocity and through-section flux conservation.

Tolerances are the checker's own; the binding test does not widen them.
"""
import math
import tempfile
import unittest
from pathlib import Path

import numpy as np
import chflow_core

ROOT = Path(__file__).resolve().parents[2]
PISO_CASE = ROOT / "tests" / "cases" / "startedChannel" / "case.dict"
SIMPLE_CASE = ROOT / "tests" / "cases" / "poiseuilleChannel" / "case.dict"

# check_piso.py constants
H, NU, FORCE, CELLS_Y = 0.2, 0.01, 0.1, 20
U_STEADY = FORCE * H * H / (2.0 * NU)
DY = H / CELLS_Y
U_EXACT_STEADY = FORCE / (2.0 * NU)


def steady(y):
    return U_EXACT_STEADY * (y * (H - y) + (DY / 2.0) ** 2)


def uProbe(xi):
    return steady(xi * H)


def exact(xi, t, nmax=200):
    s = steady(xi * H)
    for n in range(1, nmax + 1):
        b = 4.0 * (1.0 - (-1.0) ** n) / (n * math.pi) ** 3
        s -= U_STEADY * b * math.sin(n * math.pi * xi) * math.exp(
            -n * n * math.pi * math.pi * NU * t / (H * H))
    return s


MINIMAL_BLOCK = """// generated by the NS binding test
block
{{
    min   (0 0 0);
    max   (1 0.2 0.1);
    cells (4 8 1);
    xmin  {{ name left;   type symmetry; }}
    xmax  {{ name right;  type symmetry; }}
    ymin  {{ name bottom; type wall;     }}
    ymax  {{ name top;    type wall;     }}
    zmin  {{ name front;  type symmetry; }}
    zmax  {{ name back;   type symmetry; }}
}}
nu 0.01;
patches
{{
    left   {{ UType zeroGradient; p 0; pType fixedValue; }}
    right  {{ UType zeroGradient; pType zeroGradient; }}
    bottom {{ U (0 0 0); UType fixedValue; pType zeroGradient; }}
    top    {{ U (0 0 0); UType fixedValue; pType zeroGradient; }}
    front  {{ UType zeroGradient; pType zeroGradient; }}
    back   {{ UType zeroGradient; pType zeroGradient; }}
}}
schemes
{{
    ddt       Euler;
    div       upwind;
    laplacian corrected;
    grad      corrected;
}}
"""


class TestPisoNs(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.case = chflow_core.solve_piso_ns_case(str(PISO_CASE))

    def test_field_shapes(self):
        U = self.case.U
        p = self.case.p
        self.assertEqual(U.shape, (self.case.n_cells(), 3))
        self.assertEqual(p.shape, (self.case.n_cells(),))
        self.assertEqual(U.dtype, np.float64)
        self.assertEqual(p.dtype, np.float64)

    def test_history_series_and_monotone(self):
        hist = self.case.history
        self.assertGreaterEqual(len(hist), 2)
        times = [h.t for h in hist]
        self.assertTrue(all(b >= a - 1e-12 for a, b in zip(times, times[1:])))

        # the centreline probe is the cell-centre row nearest y = H/2, exactly
        # as check_piso.py does; the FVM wall offset shifts that discrete row
        # away from the continuous parabola centreline.
        centres = self.case.cell_centres()
        probe_y = min(centres[:, 1], key=lambda y: abs(y - H / 2.0))
        xiProbe = probe_y / H
        uProbe = steady(probe_y)
        rel = [abs(h.u_max - exact(xiProbe, h.t)) / max(exact(xiProbe, h.t), 1e-12)
               for h in hist]
        self.assertLess(max(rel), 2e-2, "transient history off the series")
        late = [e for h, e in zip(hist, rel) if h.t > self.case.end_time / 2.0]
        self.assertLess(max(late), 1e-5, "late history off the series")

        monotone = all(b.u_max >= a.u_max - 1e-12 for a, b in zip(hist, hist[1:]))
        self.assertTrue(monotone, "start-up overshoots or oscillates")
        overshoot = max(h.u_max for h in hist) - uProbe
        self.assertLess(abs(overshoot), 1e-6 * uProbe, "steady limit mismatch")

    def test_profile_and_continuity(self):
        centres = self.case.cell_centres()
        x0 = centres[:, 0].min()
        col = np.abs(centres[:, 0] - x0) <= 1e-9 * max(1.0, abs(x0))
        ys = centres[col, 1]
        us = self.case.U[col, 0]
        probe_y = min(centres[:, 1], key=lambda y: abs(y - H / 2.0))
        prof_err = max(abs(u - steady(y)) for y, u in zip(ys, us))
        self.assertLess(prof_err, 1e-6 * steady(probe_y), "final profile off discrete steady")

        self.assertLess(self.case.worst_continuity, 1e-12,
                        "corrected flux not divergence-free")

    def test_rejects_missing_control_block(self):
        with tempfile.TemporaryDirectory() as td:
            dict_path = Path(td) / "case.dict"
            dict_path.write_text(MINIMAL_BLOCK)
            with self.assertRaises(RuntimeError):
                chflow_core.solve_piso_ns_case(str(dict_path))

    def test_rejects_nonpositive_nu(self):
        with tempfile.TemporaryDirectory() as td:
            dict_path = Path(td) / "case.dict"
            dict_path.write_text(MINIMAL_BLOCK.replace("nu 0.01;", "nu 0;"))
            with self.assertRaises(RuntimeError):
                chflow_core.solve_piso_ns_case(str(dict_path))


class TestSimpleNs(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.case = chflow_core.solve_simple_ns_case(str(SIMPLE_CASE))

    def test_field_shapes(self):
        U = self.case.U
        self.assertEqual(U.shape, (self.case.n_cells(), 3))
        self.assertEqual(self.case.p.shape, (self.case.n_cells(),))
        self.assertEqual(U.dtype, np.float64)

    def test_poiseuille_profile(self):
        centres = self.case.cell_centres()
        U = self.case.U
        Hc, HC, UM = 0.2, 0.1, 0.1

        dev = centres[:, 0] > 3.0
        self.assertGreaterEqual(dev.sum(), 10)
        v_max = max(abs(v) for v in U[dev, 1])

        def exact(y):
            return 1.5 * UM * (1.0 - ((y - HC) / (Hc / 2.0)) ** 2)

        prof_err = max(abs(U[i, 0] - exact(centres[i, 1])) for i in np.where(dev)[0])
        u_centre = max(U[dev, 0])

        col = np.abs(centres[:, 0] - 3.5) < 0.005
        self.assertEqual(col.sum(), 20)
        dy = Hc / 20.0
        flux = float(sum(U[col, 0]) * dy)
        flux_err = abs(flux / (UM * Hc) - 1.0)

        self.assertLess(v_max, 5e-3, "transverse velocity not zero")
        self.assertLess(prof_err, 0.012, "developed profile off the parabola")
        self.assertLess(abs(u_centre / (1.5 * UM) - 1.0), 0.08, "centreline mismatch")
        self.assertLess(flux_err, 0.02, "through-section flux not conserved")

    def test_stop_signals(self):
        self.assertTrue(self.case.converged)
        self.assertGreater(self.case.iterations, 0)

    def test_rejects_missing_control_block(self):
        with tempfile.TemporaryDirectory() as td:
            dict_path = Path(td) / "case.dict"
            dict_path.write_text(MINIMAL_BLOCK)
            with self.assertRaises(RuntimeError):
                chflow_core.solve_simple_ns_case(str(dict_path))


if __name__ == "__main__":
    unittest.main()
